-- 审批时冻结的元素身份(#774 判官 r2 P1)。
--
-- 只新增一列,可空,无默认值,无约束,无索引,无回填。零破坏 —— 形状照抄同表的
-- "imageOptions"(#642 T1)。
--
-- 为什么要落盘:引擎认人那几句机器指令(`Define the product in <Image_2> as
-- <Subject_2>: 名字.`)里带着元素名,而元素名是商家随时能改的自由文本 ——
-- updateEntity 只 trim,不拦句号、换行或整句指令。名字如果由 worker 在付费调用前
-- 现读,商家批准之后改一次名,就能把没过审批的指令送进那次已经批准的付费调用。
--
-- 所以名字必须与商家看到的那张卡绑在一起:卡上冻结(商家批准前就看得见这份映射)、
-- 随付费请求走、落在这一列上,worker 只读这一列。
--
-- 形状:[{ "id": "<entityId>", "type": "CHARACTER|LOCATION|PRODUCT|BRANDMARK",
--         "name": "<批准那一刻的名字>" }],次序 = "entityIds" 的次序。
-- 解析口径的唯一实现在 @fikirtive/core 的 parseApprovedEntities —— 读不懂的条目一律
-- 丢弃,丢弃的结果是那个槽位变成无名编号句(少一个名字),而不是猜一个名字塞给模型。
--
-- 为什么零破坏:
--   ① ADD COLUMN ... JSONB(可空)不重写既有行、不长时间持锁;
--   ② 既有行保持 NULL。NULL 在读取端语义明确:这一趟没有获批的名字 → worker 编号
--      照旧,只是不写名字。降级方向是「少一个名字」,不是「多一条没批准的指令」;
--   ③ 因此不需要回填。回填只会把一个推断值写成看起来像事实的东西 —— 而这一列的
--      全部意义就是「商家当时真的看到过这个名字」,推断出来的值恰好没有这个性质;
--   ④ 幂等键行为不回归:这一列不参与幂等材料(apps/web/lib/batch-idempotency.ts),
--      所以同一次尝试的重放不会因为改过名而被判成「换了内容」;
--   ⑤ 不删列、不改列型、不加约束、不加索引 —— 没有任何数据丢失级 DDL。

ALTER TABLE "GenJob" ADD COLUMN "approvedEntities" JSONB;
