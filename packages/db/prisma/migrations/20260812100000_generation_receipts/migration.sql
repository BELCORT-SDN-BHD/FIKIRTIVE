-- 生成回执落库(#776)。两列,都可空,无默认值,无约束,无索引,无回填。零破坏。
--
-- 为什么要落盘:付费引擎在响应里报回来两件事实,我们此前**全部丢弃**——
--   ① 它真正跑的那句提示词(服务端改写/加固之后的版本);
--   ② 这一单它真收的计费量。
-- 丢掉①,商家看到的图和他写的那句话之间就少了一环,「每个东西都要有迹可循」在这条链上
-- 断了;丢掉②,毛利只能按公式估,估得对不对没有任何一处可以反查。
--
-- 这次迁移只做「记账」,不碰「计费」:
--   · "Generation"."finalPromptText" —— 引擎自报的那句提示词,商家可见(展示前过白标过滤)。
--     商家自己写的那句仍在 "Generation"."promptText",两句分开存,永不互相冒充。
--   · "GenJob"."billedUnits"        —— 引擎自报的真实计费量,与同一行的 "spentUsd"
--     (我们按公式冻结的成本估算)并排,于是两者第一次可比。内部口径,不上商家面。
-- reserve / settle / refund 的权威、幂等键、以及 CreditLedger 一个字节都没动;这两列
-- 也绝不参与任何 spend 判定。
--
-- 为什么零破坏:
--   ① ADD COLUMN ... NULL(无默认值)不重写既有行、不长时间持锁;
--   ② 现有行保持 NULL,而 NULL 的语义**就是**「引擎没报,我们不知道」——它恰好是这些
--      历史行的真相:那时我们根本没读过回执。所以不需要回填,也**不许**回填:回填只会
--      把一个推断值写成看起来像事实的东西,而这两列存在的全部理由就是不编事实;
--   ③ 不删列、不改列型、不加约束、不加索引 —— 没有任何数据丢失级 DDL。

ALTER TABLE "Generation" ADD COLUMN "finalPromptText" TEXT;
ALTER TABLE "GenJob" ADD COLUMN "billedUnits" INTEGER;
