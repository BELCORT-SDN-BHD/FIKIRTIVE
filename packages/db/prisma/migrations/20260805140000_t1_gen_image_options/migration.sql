-- T1 图片规格快照列(#642 · spec #641 分片 T1)。
--
-- 只新增一列,可空,无默认值,无约束,无索引,无回填。零破坏。
--
-- 为什么要落盘:图片链路上「规格」这个概念本来不存在 —— 契约没有字段、库里没有列、
-- 适配器写死方图。商家要竖版,拿到的是方图,而且没有任何一处记录下他要过什么。视频侧
-- 早就有 "videoOptions" 这一列在做同一件事(入队时冻结商家选的规格,worker 读回来发给
-- 引擎),这里照抄那个形状。
--
-- 这一列同时是「改这张图 / 再来一张」继承源图画幅的**唯一**依据:重做一张图时,画幅从
-- 源图那一单的这份快照读回来,而不是去反推像素。
--
-- 为什么零破坏:
--   ① ADD COLUMN ... Json?(Postgres jsonb,可空)不重写既有行、不长时间持锁;
--   ② 现有行保持 NULL。NULL 的语义在读取端是明确的 —— 这些行当年产出的就是默认方图,
--      所以读取端按默认画幅(1:1 / 2048×2048)解释它们,与它们真实的历史产出一致;
--   ③ 因此不需要回填。回填只会把一个推断值写成看起来像事实的东西。
--   ④ 幂等键行为不回归:材料比对把「NULL」与「显式的默认画幅」视为同一份材料
--      (apps/web/lib/batch-idempotency.ts),所以老作业重放不会被误判成材料冲突。
--   ⑤ 不删列、不改列型、不加约束、不加索引 —— 这次迁移没有任何数据丢失级 DDL。

ALTER TABLE "GenJob" ADD COLUMN "imageOptions" JSONB;
