-- #782 分镜自动接续:一列末帧指针。
--
-- 只新增一列,可空,无默认值,无约束,无索引,无回填。零破坏。
--
-- 为什么要落盘:视频引擎可以在出片时**免费**附送这条片子的末帧静图
-- (`return_last_frame`,与片子同一次渲染,不另计价)。分镜链要让第 N+1 镜头真的从第 N 镜头
-- 停住的那一帧起步,就必须把这张静图在**出片当时**接住 —— 事后再问引擎要,片子早已交付,
-- 那一帧就永远拿不回来了。所以捕获点在 worker,落点在这一列。
--
-- 为什么指向 Asset 而不是 Generation:Generation 是「一件作品」,会出现在候选区与素材面前;
-- 末帧在被下一镜头真的用上之前只是一份素材。等分镜闸③ 真的把它灌进下一镜头首帧时,那一刻
-- 才铸 Generation 行 —— 在此之前商家的候选区不会平白多出 N 张没人要过的静图。
--
-- 为什么零破坏:
--   ① ADD COLUMN ... TEXT(可空、无默认)不重写既有行、不长时间持锁;
--   ② 现有行保持 NULL,语义明确且**已经**是读取端的正常分支:「这一单没有末帧」
--      (图片作业、#782 之前的老作业、引擎没给、下载失败,四种情况同一条路);
--   ③ 因此不需要回填 —— 历史片子的末帧本来就没被接住过,回填只能编;
--   ④ 不建外键:Asset 是内容寻址的共享行(同哈希同一行),这一列是**软引用**,与
--      GenJob.sourceGenerationId / tailGenerationId 同一家法(worker/action 侧按 owner 复核);
--   ⑤ 不删列、不改列型、不加约束、不加索引 —— 没有任何数据丢失级 DDL。
--   ⑥ 钱路一格不动:这一列既不参与预扣/结算/退款,也不参与任何计价读法。

ALTER TABLE "GenJob" ADD COLUMN "lastFrameAssetId" TEXT;
