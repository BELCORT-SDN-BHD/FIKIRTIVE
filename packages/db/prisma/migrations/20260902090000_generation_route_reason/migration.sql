-- 能力路由的理由落盘(Creation 引擎 S2 §8.1①,验收 CREATE-A4 / CREATE-A12)。
--
-- ── 为什么一列自由文本值得一次迁移 ────────────────────────────────────────────
-- 本片让引擎第一次**替商家挑档位**:商家说「要 1080p」,引擎就把这一单送去高清槽位,
-- 而那一档比默认档贵五倍。规格 §4 异议栏把这件事点名成本片最大的风险之一 ——
-- 「能力路由替商家挑档 = 替商家花钱」,对策三条:报价前置(A4)、白名单 fail closed
-- (A5/A6)、**路由理由只认商家可见的能力名词并且可查**(九问4 + A12)。
-- 第三条要成立,理由就不能只在提交那一刻的界面上闪一下:商家事后问「这条片为什么
-- 收了 55 credits」,答案必须在**这一行**上,而不是靠事后重新推断一次。
--
-- ── 这一列里写什么、不写什么 ──────────────────────────────────────────────────
-- 写:能力名词的一句人话,例如 "You asked for 1080p, so this went to the HD tier."
-- 不写:任何型号名(S1 九问4「商家永远只见能力,不见型号」;`provider-secrecy` 是兜底,
--      不是许可证)。值由纯函数 `routeReasonFor()` 现算 —— 请求侧报价说的那一句与
--      worker 落库写的这一句是**同一个函数**,所以两边不可能分家。
--
-- ── 为什么可空、零回填 ────────────────────────────────────────────────────────
-- NULL 有两种来路,语义相同,都是「这一行没有升档理由可说」:
--   ①这一行早于本列存在(历史生成);
--   ②这一趟走的是默认槽位 —— 没有发生升档,没什么可解释的。
-- 存量行**一行不动**:回填只会把推断值写成看起来像事实的东西(与 sentPromptText
-- 那一列同一条纪律)。所以这份迁移不 UPDATE 任何一行、不删任何数据、不改任何约束,
-- 只有一个可重跑的 ADD COLUMN IF NOT EXISTS —— 不需要备份/恢复预案。

BEGIN;

ALTER TABLE "Generation" ADD COLUMN IF NOT EXISTS "routeReason" TEXT;

COMMIT;
